"""Normalize VERIFIED workbooks. Relative follow-up is never a fabricated date.

The DIMS workbook publishes months since baseline, not calendar dates. The
canonical extension followup_month preserves that information; visit_date stays
missing. Unreviewed workbook structures fail rather than guessing column names.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.ml.dataset import OPTIONAL_COLUMNS, load_visits  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def normalize_dims(path: Path) -> pd.DataFrame:
    df = pd.read_excel(path, sheet_name="Sheet1")
    expected = ["Px_ID", "Age", "Gender"] + [f"{m}_{h}" for m in ("SER", "AL")
                for h in ("BL", "3M", "6M", "9M", "12M", "24M", "36M")]
    missing = set(expected) - set(df)
    if missing:
        raise ValueError(f"Unreviewed DIMS structure: missing {missing}")
    if df.Px_ID.duplicated().any():
        raise ValueError("Duplicate DIMS subject IDs")
    records = []
    for row in df.to_dict("records"):
        for month in (0, 3, 6, 9, 12, 24, 36):
            suffix = "BL" if month == 0 else f"{month}M"
            records.append({"patient_key": f"dims:{row['Px_ID']}", "visit_date": None,
                            "followup_month": month, "age": row["Age"] if month == 0 else np.nan,
                            "sex": None, "spherical_equivalent": row[f"SER_{suffix}"],
                            "axial_length": row[f"AL_{suffix}"], "treatment": "dims",
                            "source": "Zenodo DIMS 36-month (18166476)"})
    return pd.DataFrame(records)


def build(raw: Path, out: Path, card: Path) -> dict:
    manifest = json.loads((raw / "manifest.json").read_text(encoding="utf-8"))
    frames = []
    decisions = []
    if "dims" in manifest:
        f = raw / "dims" / "DataSet.xlsx"
        if hashlib.sha256(f.read_bytes()).hexdigest() != manifest["dims"]["sha256"]:
            raise ValueError("DIMS file changed since verification")
        frames.append(normalize_dims(f))
    if "dryad_3year" in manifest:
        # Explicit inspection output makes an unsupported source reviewable.
        f = raw / "dryad_3year" / "Data3.xlsx"
        x = pd.ExcelFile(f)
        columns = {s: list(map(str, pd.read_excel(f, sheet_name=s).columns)) for s in x.sheet_names}
        raise ValueError(f"Dryad adapter requires workbook review before use. Actual columns: {columns}")
    decisions.append("Shanghai c2fqz615c excluded: independent 2014/2018 school samples; longitudinal linkage unverified.")
    if not frames:
        raise ValueError("No verified supported longitudinal source. Run fetch_datasets.py; no synthetic fallback.")
    df = pd.concat(frames, ignore_index=True)
    for col in OPTIONAL_COLUMNS:
        if col not in df:
            df[col] = np.nan
    out.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(out, index=False, lineterminator="\n")
    validated = load_visits(out)
    report = {"data_is_synthetic": False, "sources": [manifest[k] for k in manifest if k == "dims"],
              "source_names": sorted(validated.source.unique().tolist()),
              "n_patients": int(validated.patient_key.nunique()), "n_visits": len(validated),
              "missingness": {c: round(float(validated[c].isna().mean()), 4) for c in validated},
              "followup_months": [float(validated.followup_month.min()), float(validated.followup_month.max())],
              "per_source": validated.groupby("source").agg(n_patients=("patient_key", "nunique"), n_visits=("patient_key", "size")).to_dict("index"),
              "table_sha256": hashlib.sha256(out.read_bytes()).hexdigest(),
              "decisions": decisions,
              "limitations": ["Only 20 DIMS subjects; very small patient-level holdout; not clinical validation.",
                  "SER is interpreted in diopters and AL in millimeters from field names, study context and value ranges; no separate units/eye-selection codebook was published with this workbook. Values are not converted.",
                  "Calendar dates absent: visit_date remains null; scheduled follow-up months are preserved.",
                  "Age recorded at baseline only; later ages remain missing. Gender B/G lacks a supplied codebook and is left missing.",
                  "No behavioural/ergonomic measurements. No treatment-effect inference from an all-DIMS cohort.",
                  "Peripheral refraction is retained in the raw workbook but excluded from the shared clinical model."]}
    out.with_suffix(".provenance.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    card.parent.mkdir(parents=True, exist_ok=True)
    card.write_text("# Data card\n\nGenerated by build_training_table.py from checksum-verified files.\n\n"
                    "## Used for training and open-record seeding\n\n"
                    "[Zenodo DIMS 36-month dataset](https://zenodo.org/records/18166476), "
                    "[original workbook](https://zenodo.org/records/18166476/files/DataSet.xlsx?download=1), "
                    "CC BY 4.0 (verified in the repository API metadata). "
                    "Sheet1 has 20 subject rows and 139 columns. Px_ID links seven scheduled "
                    "measurements: baseline, 3, 6, 9, 12, 24 and 36 months. SER_* and AL_* "
                    "are used, together with baseline Age. Gender is B/G without a supplied "
                    "codebook, so normalized sex stays missing. Peripheral-refraction fields "
                    "and the repeated-position poly sheet are not independent subjects and "
                    "are excluded. The workbook is retained unmodified with attribution in "
                    "backend/data/open/SOURCES.md.\n\n"
                    "Units: SER is interpreted as D (negative myopic) and AL as mm from the "
                    "field names, study context and observed ranges. No independent units "
                    "or eye-selection codebook was supplied; this remains a limitation. "
                    "No unit conversions or invented calendar dates/ages/exposures are used.\n\n"
                    "## Inspected metadata only; not used\n\n"
                    "- [Dryad three-year cohort](https://doi.org/10.5061/dryad.d4mb3pn): "
                    "452 children per the study metadata, CC0 per repository metadata. "
                    "Download returned HTML; authenticated API download returned 401. "
                    "Workbook headers, patient/eye linkage and missingness are unverified. "
                    "The adapter fails explicitly pending inspection of Data3.xlsx.\n"
                    "- [Dryad Shanghai 2014/2018](https://doi.org/10.5061/dryad.c2fqz615c): "
                    "CC0 per repository metadata; independently sampled schools in two "
                    "years are described. Download failed verification. No longitudinal "
                    "linkage is established, so it is excluded from training and validation. "
                    "Lifestyle questionnaires are mentioned in the abstract, but no "
                    "workbook variables have been verified or used.\n\n"
                    "The following report includes all canonical missingness and checksums.\n\n" +
                    "```json\n" + json.dumps(report, indent=2) + "\n```\n", encoding="utf-8")
    return report


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--raw", type=Path, default=ROOT / "data/raw")
    p.add_argument("--out", type=Path, default=ROOT / "data/training_visits.csv")
    p.add_argument("--card", type=Path, default=ROOT.parent / "docs/DATA_CARD.md")
    a = p.parse_args()
    print(json.dumps(build(a.raw, a.out, a.card), indent=2))
