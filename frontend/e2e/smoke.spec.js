// Isolated test database only. Entered measurements are test fixtures.
import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('patient auth, record entry, version update, simulator and role gate', async ({ page }) => {
  await page.goto('/signup')
  await page.getByLabel('Your name').fill('Smoke test account')
  await page.getByLabel(/^Email/).fill(`smoke-${Date.now()}@example.org`)
  await page.getByLabel(/^Password/).fill('isolated-test-2026')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page).toHaveURL(/\/app$/)
  await page.goto('/app/records?add=1')
  await page.getByLabel('Date of test').fill('2020-01-01')
  await page.getByRole('spinbutton', { name: /^Prescription/ }).fill('-1.5')
  await page.getByRole('spinbutton', { name: /^Eye length/ }).fill('24')
  await page.getByRole('button', { name: /Save/ }).click()
  await expect(page.getByText('Twin updated to v1')).toBeVisible()
  await page.goto('/app/cohort')
  await expect(page).toHaveURL(/\/app$/)
  await page.goto('/try')
  await page.getByRole('spinbutton', { name: /^Age/ }).fill('10')
  await page.getByRole('spinbutton', { name: /^Prescription/ }).fill('-1.5')
  await page.getByRole('button', { name: /Show|Project|See/ }).last().click()
  await expect(page.getByText('Model estimate', { exact: false }).first()).toBeVisible()
})

test('clinician cohort, patient detail, evidence trace and mobile layout', async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel(/^Email/).fill('clinician-smoke@example.org')
  await page.getByLabel(/^Password/).fill('isolated-clinician-2026')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Patient cohort' })).toBeVisible()
  await page.getByRole('link', { name: 'dims:D1', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Current twin' })).toBeVisible()
  // The published D1 month-36 visit was withheld from this isolated seed.
  await page.getByRole('spinbutton', { name: /^Source-recorded month/ }).fill('36')
  await page.getByRole('spinbutton', { name: /^Spherical equivalent/ }).fill('-5.13')
  await page.getByRole('spinbutton', { name: /^Axial length/ }).fill('26.89')
  const saved = page.waitForResponse(r => r.url().includes('/observations') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Save observation' }).click()
  const observationResult = await (await saved).json()
  expect(observationResult.twin_version).toBe(7)
  expect(observationResult.twin.prediction.horizons['12m'].se.value).toEqual(expect.any(Number))
  expect(observationResult.twin.monitor).toBeTruthy()
  await expect(page.getByText('Twin v7', { exact: false })).toBeVisible()
  await expect(page.getByText('Monitor:', { exact: false }).first()).toBeVisible()
  await page.getByLabel('Question').fill('What published evidence relates to myopia?')
  await page.getByRole('button', { name: 'Ask the twin' }).click()
  await expect(page.getByText('retrieve_evidence', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Compare latest versions' }).click()
  await page.getByRole('button', { name: 'Check scenario availability' }).click()
  await expect(page.getByText('No numeric treatment', { exact: false }).first()).toBeVisible()
  await page.screenshot({ path: 'test-results/clinician-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForTimeout(500)
  await page.screenshot({ path: 'test-results/clinician-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze()
  expect(result.violations.filter(v => v.id !== 'color-contrast')).toEqual([])
  await page.goto('/app/model')
  await expect(page.getByRole('heading', { name: 'Model card' })).toBeVisible()
  await expect(page.getByText('no demonstrated clinical utility', { exact: false }).first()).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Additional research datasets' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Five-year onset research model' })).toBeVisible()
  await expect(page.getByRole('columnheader', { name: 'Sensitivity', exact: true })).toBeVisible()
  await expect(page.getByText('Overall accuracy above 95% has not been achieved.', { exact: false })).toBeVisible()
  await page.getByText('Try an onset research estimate', { exact: true }).click()
  await page.getByRole('spinbutton', { name: /^Baseline age/ }).fill('6')
  await page.getByRole('spinbutton', { name: /^Baseline spherical equivalent/ }).fill('0.608')
  await page.getByRole('spinbutton', { name: /^Measured baseline axial length/ }).fill('22.38')
  await page.getByRole('button', { name: 'Estimate five-year onset association' }).click()
  await expect(page.getByText('Five-year onset estimate:', { exact: false })).toBeVisible()
})
